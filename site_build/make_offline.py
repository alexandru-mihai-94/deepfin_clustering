"""
Write deepfin_clustering/docs/sw.js: the offline cache that lets the exhibit run as a home-screen
web app on an iPad with no network.

It pre-caches the home page and the three activity pages, the manifest, the icons and every file in ai_eye/, spot_species/
and stages/. Pages are served from the cache at once and refreshed from the network in the
background, so an edit shows up on the next load whenever the iPad is online. Rerun this after
adding, removing or changing files: the cache version is a hash of their contents, so installed
iPads then fetch the whole new set.

    site_build/venv/bin/python site_build/make_offline.py
"""
import hashlib, json
from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent / "docs"
files = ["index.html", "how_ai_sees.html", "spot_the_species.html", "stages.html", "manifest.webmanifest"]
for d in ("ai_eye", "spot_species", "stages", "icons"):
    files += sorted(f"{d}/{p.name}" for p in (DOCS / d).iterdir() if p.is_file() and not p.name.startswith("."))

h = hashlib.sha1()
for f in files:
    h.update(f.encode()); h.update((DOCS / f).read_bytes())

(DOCS / "sw.js").write_text(f"""// generated by site_build/make_offline.py: rerun it after changing any page or image
const CACHE = 'deepfin-{h.hexdigest()[:10]}';
const FILES = {json.dumps(files)};

self.addEventListener('install', e => e.waitUntil(
  caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())));

self.addEventListener('activate', e => e.waitUntil(
  caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim())));

// answer from the cache at once (works offline); refresh that file from the network in the background
self.addEventListener('fetch', e => {{
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.open(CACHE).then(async c => {{
    const hit = await c.match(e.request, {{ ignoreSearch: true }});
    const net = fetch(e.request).then(r => {{ if (r.ok) c.put(e.request, r.clone()); return r; }}).catch(() => hit);
    return hit || net;
  }}));
}});
""")
size = sum((DOCS / f).stat().st_size for f in files)
print(f"wrote {DOCS / 'sw.js'}: {len(files)} files, {size / 1e6:.1f} MB, version {h.hexdigest()[:10]}")
